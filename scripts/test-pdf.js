#!/usr/bin/env node
/*
 * Builds a sample PDF from the current inventory so you can check the layout
 * without sending any email.
 *
 *   npm run build && npm run test:pdf
 *   node scripts/test-pdf.js path/to/output.pdf
 */
const fs = require("fs");
const path = require("path");
const { validate } = require("../netlify/lib/validate");
const { buildPdf } = require("../netlify/lib/pdf");

const invPath = path.join(__dirname, "..", "netlify", "lib", "inventory.json");
if (!fs.existsSync(invPath)) {
  console.error("Run `npm run build` first to generate the inventory.");
  process.exit(1);
}
const inventory = JSON.parse(fs.readFileSync(invPath, "utf8"));

// First item from each category, up to 10
const seen = new Set();
const items = [];
for (const it of inventory.items) {
  if (seen.has(it.category)) continue;
  seen.add(it.category);
  items.push({ id: it.id, qty: Math.min(2, it.available) });
  if (items.length >= 10) break;
}

const { errors, clean } = validate(
  {
    project: "Sample shoot",
    shootDate: "2030-06-12",
    pickupDate: "2030-06-11",
    returnDate: "2030-06-14",
    main: { first: "Alex", last: "Rivera", email: "alex.rivera@goldenhippo.com" },
    additional: [{ first: "Sam", last: "Lee", email: "sam.lee@goldenhippo.com" }],
    items,
    notes: "Sample request generated by scripts/test-pdf.js.",
  },
  inventory,
  { today: "2030-01-01" }
);
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

buildPdf({ ...clean, ref: "ER-SAMPLE-0001", submittedAt: new Date() }).then((buf) => {
  const out = path.resolve(process.argv[2] || "sample-request.pdf");
  fs.writeFileSync(out, buf);
  console.log(`Wrote ${out} (${buf.length} bytes)`);
});
